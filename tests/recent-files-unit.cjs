const assert = require('node:assert/strict');
const { read, record } = require('../js/recent-files.js');
const data = new Map();
const storage = { getItem: key => data.get(key), setItem: (key, value) => data.set(key, value) };
const file = { boardId: 'board', itemId: 'item', columnId: 'column', fileKey: 'file', name: 'Teste.pdf', authToken: 'nao-guardar', url: 'nao-guardar' };
record(storage, 'one', file, 1);
assert.equal(read(storage, 'one').length, 1);
assert.equal(read(storage, 'two').length, 0);
record(storage, 'one', file, 2);
assert.equal(read(storage, 'one').length, 1);
assert.equal(read(storage, 'one')[0].openedAt, 2);
assert(!JSON.stringify([...data.values()]).includes('nao-guardar'));
for (let index = 0; index < 20; index++) record(storage, 'one', { ...file, fileKey: String(index) }, index + 3);
assert.equal(read(storage, 'one').length, 12);
assert.equal(read(storage, 'one')[0].fileKey, '19');
const broken = { getItem() { throw new Error('bloqueado'); }, setItem() { throw new Error('cheio'); } };
assert.deepEqual(read(broken, 'one'), []);
assert.doesNotThrow(() => record(broken, 'one', file));
assert.deepEqual(read(storage, ''), []);
record(storage, 'boards', { kind: 'board', boardId: 'b', fileKey: 'board:b', name: 'Quadro' });
assert.equal(read(storage, 'boards')[0].kind, 'board');
record(storage, 'boards', { kind: 'board', boardId: 'b', fileKey: 'board:b', name: 'Renomeado' });
assert.equal(read(storage, 'boards').length, 1);
assert.equal(read(storage, 'boards')[0].name, 'Renomeado');
console.log('Arquivos recentes: isolamento, ordem, deduplicacao, limite e dados minimos aprovados.');
