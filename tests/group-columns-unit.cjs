const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../js/v2.js'), 'utf8');
const helpers = source.slice(source.indexOf('  function columnAppliesToGroup('), source.indexOf('  function renderGroupTable('));
const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(helpers, sandbox);
const shared = { id: 'shared' };
const scoped = { id: 'scoped', settings: { group_id: 'one' } };
const board = { columns: [shared, scoped] };
assert.equal(sandbox.columnAppliesToGroup(shared, 'two'), true);
assert.equal(sandbox.columnAppliesToGroup(scoped, 'one'), true);
assert.equal(sandbox.columnAppliesToGroup(scoped, 'two'), false);
assert.equal(sandbox.columnAppliesToGroup(scoped, undefined), false);
assert.deepEqual(Array.from(sandbox.columnsForGroup(board, 'one'), x => x.id), ['shared', 'scoped']);
assert.deepEqual(Array.from(sandbox.columnsForGroup(board, 'two'), x => x.id), ['shared']);
const settings = { group_id: 'one', versionado: true };
const mapping = source.slice(source.indexOf('  function mapRemoteColumn('), source.indexOf('  function mapRemoteItemTree('));
Object.assign(sandbox, { COLUMN_TYPES: { text: { width: 160 } }, normalizeStatusOptions: x => x });
vm.runInContext(mapping, sandbox);
assert.equal(sandbox.mapRemoteColumn({ id: 'c', tipo: 'text', configuracoes: settings }).settings.group_id, 'one');
const form = source.slice(source.indexOf('  function openColumnModal('), source.indexOf('  function updateColumnEditorVisibility('));
assert(form.includes('Setor da coluna'));
assert(form.includes('Todos os setores'));
assert(form.includes('existing?.settings?.group_id === entry.id'));
const groupTable = source.slice(source.indexOf('  function renderGroupTable('), source.indexOf('  function renderItemRows('));
assert(groupTable.includes('columnsForGroup(boardEntry, groupEntry.id)'));
assert(!groupTable.includes('boardEntry.columns'));
const sectorTable = source.slice(source.indexOf('  function renderWorkSectorTable('), source.indexOf('  function renderSectorizedWorks('));
assert(sectorTable.includes('columnsForGroup(boardEntry, workItem.groupId)'));
assert(!sectorTable.includes('boardEntry.columns'));
console.log('Colunas por setor: compatibilidade, selecao, persistencia e tabelas OK');
