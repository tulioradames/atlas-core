const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const app = fs.readFileSync(path.join(__dirname, '../js/v2.js'), 'utf8');
const start = app.indexOf('  function storageForContext(');
const end = app.indexOf('  function assignStorageConnectionToMatchingScope', start);
const central = { id: 'central', type: 'local', centralized: true, status: 'connected' };
const context = { board: { storageConnectionId: 'legacy' }, module: {}, workspace: {} };
const sandbox = { runtime: { data: { storageConnections: [{ id: 'legacy', type: 'drive', status: 'connected' }, central] } }, storageType: entry => entry.type, findBoard: () => context };
vm.createContext(sandbox); vm.runInContext(app.slice(start, end) + '\nresult=storageForContext();', sandbox);
assert.equal(sandbox.result.id, 'central');
central.status = 'disabled'; vm.runInContext('result=storageForContext();', sandbox); assert.equal(sandbox.result, null);
const create = app.slice(app.indexOf('  function openCreateModal('), app.indexOf('  function choice('));
assert(!create.includes('storage-mode')); assert(!create.includes('driveExistingId'));
const submit = app.slice(app.indexOf('  function submitCreate('), app.indexOf('  function createBoardFromTemplate('));
assert(!submit.includes('validateStorageDraft')); assert(!submit.includes('storageConnectionId: workspace.storageConnectionId'));
const admin = app.slice(app.indexOf('  function renderAdminSystem('), app.indexOf('  async function runSystemHealthCheck('));
assert(!admin.includes('admin-new-storage')); assert(!admin.includes('admin-edit-storage'));
assert(admin.includes('Servidor central'));
console.log('Central: destino unico local, sem fallback legado para upload ou configuracao individual OK');
